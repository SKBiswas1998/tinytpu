a('class AsyncPipeline:')
a('    """')
a('    Threaded capture -> inference -> control pipeline.')
a('')
a('    Problem: At 1-3 FPS inference, if capture blocks on inference,')
a('    you get 1-3 Hz control. Robot is blind between frames.')
a('')
a('    Solution: Three threads:')
a('      1. Capture thread: grabs frames as fast as camera allows')
a('      2. Inference thread: processes latest frame when ready')
a('      3. Control runs at fixed rate using Kalman predictions')
a('')
a('    Control loop runs at target_hz (default 30) even when')
a('    inference runs at 2 FPS.')
a('    """')
a('')
a('    def __init__(self,')
a('                 detector: ObjectDetector,')
a('                 controller: RobotController,')
a('                 tracker: ObjectTracker = None,')
a('                 safety: SafetyController = None,')
a('                 thermal: ThermalMonitor = None,')
a('                 target_hz: float = 30.0):')
a('        self.detector = detector')
a('        self.controller = controller')
a('        self.tracker = tracker or ObjectTracker()')
a('        self.safety = safety or SafetyController()')
a('        self.thermal = thermal')
a('        self.target_hz = target_hz')
a('')
a('        # Shared state (protected by locks)')
a('        self._frame_lock = threading.Lock()')
a('        self._result_lock = threading.Lock()')
a('        self._latest_frame = None')
a('        self._frame_id = 0')
a('        self._last_processed_id = -1')
a('        self._latest_detections: List[Detection] = []')
a('        self._latest_command = RobotCommand(0, 0, 0, "startup", "Initializing")')
a('        self._img_w = 640')
a('        self._img_h = 480')
a('')
a('        # Stats')
a('        self.inference_fps = 0.0')
a('        self.control_fps = 0.0')
a('        self.capture_fps = 0.0')
a('        self.frames_captured = 0')
a('        self.frames_inferred = 0')
a('        self.frames_skipped = 0')
a('')
a('        self._running = False')
a('        self._threads = []')
a('')
a('    def push_frame(self, frame: np.ndarray):')
a('        """Push a new camera frame. Non-blocking."""')
a('        with self._frame_lock:')
a('            self._latest_frame = frame')
a('            self._frame_id += 1')
a('            self._img_h, self._img_w = frame.shape[:2]')
a('        self.frames_captured += 1')
a('')
a('    def get_command(self) -> RobotCommand:')
a('        """Get latest safe robot command. Non-blocking."""')
a('        with self._result_lock:')
a('            return self._latest_command')
a('')
a('    def get_detections(self) -> List[Detection]:')
a('        """Get latest tracked detections. Non-blocking."""')
a('        with self._result_lock:')
a('            return list(self._latest_detections)')
a('')
a('    def _inference_loop(self):')
a('        """Inference thread: process latest frame when available."""')
a('        last_time = time.monotonic()')
a('        while self._running:')
a('            # Get latest frame')
a('            with self._frame_lock:')
a('                frame = self._latest_frame')
a('                frame_id = self._frame_id')
a('')
a('            if frame is None or frame_id == self._last_processed_id:')
a('                time.sleep(0.001)')
a('                continue')
a('')
a('            # Thermal skip')
a('            skip = 0')
a('            if self.thermal:')
a('                skip = self.thermal.get_skip_factor()')
a('            if skip > 0 and frame_id % (skip + 1) != 0:')
a('                self.frames_skipped += 1')
a('                time.sleep(0.01)')
a('                continue')
a('')
a('            # Run detection')
a('            detections = self.detector.detect(frame)')
a('            self._last_processed_id = frame_id')
a('            self.frames_inferred += 1')
a('')
a('            # Feed watchdog')
a('            self.safety.feed_watchdog()')
a('')
a('            # Update tracker')
a('            tracks = self.tracker.update(detections)')
a('            tracked_dets = self.tracker.get_detections(tracks)')
a('')
a('            # Update shared state')
a('            with self._result_lock:')
a('                self._latest_detections = tracked_dets')
a('')
a('            # FPS')
a('            now = time.monotonic()')
a('            dt = now - last_time')
a('            if dt > 0:')
a('                self.inference_fps = 0.9 * self.inference_fps + 0.1 * (1.0 / dt)')
a('            last_time = now')
a('')
a('    def _control_loop(self):')
a('        """Control thread: runs at target_hz using Kalman predictions."""')
a('        period = 1.0 / self.target_hz')
a('        last_time = time.monotonic()')
a('')
a('        while self._running:')
a('            loop_start = time.monotonic()')
a('')
a('            # Get Kalman-predicted detections (fast, no inference)')
a('            predicted_tracks = self.tracker.predict()')
a('            predicted_dets = self.tracker.get_detections(predicted_tracks)')
a('')
a('            # Run controller')
a('            with self._result_lock:')
a('                img_w, img_h = self._img_w, self._img_h')
a('')
a('            raw_cmd = self.controller.update(predicted_dets, img_w, img_h)')
a('')
a('            # Safety filter')
a('            safe_cmd = self.safety.filter_command(raw_cmd, predicted_dets, img_w, img_h)')
a('')
a('            with self._result_lock:')
a('                self._latest_command = safe_cmd')
a('                self._latest_detections = predicted_dets')
a('')
a('            # FPS')
a('            now = time.monotonic()')
a('            dt = now - last_time')
a('            if dt > 0:')
a('                self.control_fps = 0.9 * self.control_fps + 0.1 * (1.0 / dt)')
a('            last_time = now')
a('')
a('            # Sleep to maintain target rate')
a('            elapsed = time.monotonic() - loop_start')
a('            sleep_time = period - elapsed')
a('            if sleep_time > 0:')
a('                time.sleep(sleep_time)')
a('')
a('    def start(self):')
a('        """Start inference and control threads."""')
a('        self._running = True')
a('        if self.thermal:')
a('            self.thermal.start()')
a('')
a('        t_inf = threading.Thread(target=self._inference_loop, daemon=True, name="inference")')
a('        t_ctrl = threading.Thread(target=self._control_loop, daemon=True, name="control")')
a('        t_inf.start()')
a('        t_ctrl.start()')
a('        self._threads = [t_inf, t_ctrl]')
a('        logger.info("AsyncPipeline started: inference + control threads")')
a('')
a('    def stop(self):')
a('        self._running = False')
a('        if self.thermal:')
a('            self.thermal.stop()')
a('        for t in self._threads:')
a('            t.join(timeout=5)')
a('        logger.info("AsyncPipeline stopped")')
a('')
a('    def get_status(self) -> dict:')
a('        return {')
a('            "inference_fps": round(self.inference_fps, 1),')
a('            "control_fps": round(self.control_fps, 1),')
a('            "frames_captured": self.frames_captured,')
a('            "frames_inferred": self.frames_inferred,')
a('            "frames_skipped": self.frames_skipped,')
a('            "tracker": self.tracker.get_status(),')
a('            "safety": self.safety.get_status(),')
a('        }')

