a('## Design Philosophy')
a('')
a('TinyTPU makes three deliberate choices that differ from mainstream edge AI frameworks:')
a('')
a('**1. Vertical integration over modularity.** Rather than being a great inference engine that requires separate tracking, safety, and control libraries, TinyTPU provides the complete stack. A single `ProductionEdgeAI.auto()` call gives you detection, tracking, safety, thermal management, memory protection, and motor commands. This eliminates the integration work that delays robotics deployments.')
a('')
a('**2. Honesty over benchmarks.** The README reports real FPS on real hardware, including cases where performance is poor. A Pi 4 gets 0.8 FPS with YOLOv5s. That is too slow for real-time obstacle avoidance. Rather than hiding this, TinyTPU acknowledges it and provides Kalman prediction, async pipelines, and frame skipping as mitigation. Knowing the constraints is more useful than optimistic numbers.')
a('')
a('**3. Safety by default, not by option.** Every motor command passes through the safety controller. There is no way to bypass it without explicitly removing it. The watchdog, thermal monitor, and memory guard are always active in `ProductionEdgeAI`. A hobby demo can skip them using `EdgeAI.auto()`, but any production deployment includes all safety layers automatically.')
