a('class ImageQualityScorer:')
a('    """')
a('    Fast image quality assessment for camera health monitoring.')
a('')
a('    Detects:')
a('      - Blur (Laplacian variance)')
a('      - Darkness / overexposure (histogram analysis)')
a('      - Low contrast (histogram spread)')
a('      - Occlusion (uniform regions)')
a('')
a('    Returns quality score 0-100 and per-issue flags.')
a('    All computed with numpy only (no OpenCV required).')
a('    """')
a('')
a('    def __init__(self,')
a('                 blur_threshold: float = 50.0,')
a('                 dark_threshold: float = 40.0,')
a('                 bright_threshold: float = 220.0,')
a('                 contrast_threshold: float = 30.0):')
a('        self.blur_threshold = blur_threshold')
a('        self.dark_threshold = dark_threshold')
a('        self.bright_threshold = bright_threshold')
a('        self.contrast_threshold = contrast_threshold')
a('        self.history = deque(maxlen=100)')
a('')
a('    def score(self, image: np.ndarray) -> dict:')
a('        """')
a('        Score image quality.')
a('')
a('        Returns:')
a('            {"score": 0-100, "blur": float, "brightness": float,')
a('             "contrast": float, "issues": ["dark", "blurry", ...],')
a('             "usable": bool}')
a('        """')
a('        if image is None or image.size == 0:')
a('            return {"score": 0, "issues": ["no_image"], "usable": False,')
a('                    "blur": 0, "brightness": 0, "contrast": 0}')
a('')
a('        # Convert to grayscale if needed')
a('        if image.ndim == 3:')
a('            gray = np.mean(image, axis=2).astype(np.float32)')
a('        else:')
a('            gray = image.astype(np.float32)')
a('')
a('        # Downsample for speed')
a('        h, w = gray.shape')
a('        if h > 120:')
a('            step = h // 120')
a('            gray = gray[::step, ::step]')
a('')
a('        issues = []')
a('        scores = []')
a('')
a('        # 1. Blur detection (Laplacian variance)')
a('        # Laplacian kernel: [[0,1,0],[1,-4,1],[0,1,0]]')
a('        laplacian = np.zeros_like(gray)')
a('        laplacian[1:-1, 1:-1] = (')
a('            gray[0:-2, 1:-1] + gray[2:, 1:-1] +')
a('            gray[1:-1, 0:-2] + gray[1:-1, 2:] -')
a('            4 * gray[1:-1, 1:-1]')
a('        )')
a('        blur_score = float(np.var(laplacian))')
a('        if blur_score < self.blur_threshold:')
a('            issues.append("blurry")')
a('        blur_quality = min(100, blur_score / self.blur_threshold * 100)')
a('        scores.append(blur_quality)')
a('')
a('        # 2. Brightness')
a('        mean_brightness = float(np.mean(gray))')
a('        if mean_brightness < self.dark_threshold:')
a('            issues.append("dark")')
a('            bright_quality = mean_brightness / self.dark_threshold * 100')
a('        elif mean_brightness > self.bright_threshold:')
a('            issues.append("overexposed")')
a('            bright_quality = max(0, (255 - mean_brightness) / (255 - self.bright_threshold) * 100)')
a('        else:')
a('            bright_quality = 100')
a('        scores.append(bright_quality)')
a('')
a('        # 3. Contrast (std dev of brightness)')
a('        contrast = float(np.std(gray))')
a('        if contrast < self.contrast_threshold:')
a('            issues.append("low_contrast")')
a('        contrast_quality = min(100, contrast / self.contrast_threshold * 100)')
a('        scores.append(contrast_quality)')
a('')
a('        # 4. Uniform region detection (possible occlusion)')
a('        # Check if >50% of image is very similar')
a('        hist_range = np.ptp(gray)  # peak to peak')
a('        if hist_range < 15:')
a('            issues.append("occluded")')
a('            scores.append(20)')
a('        else:')
a('            scores.append(100)')
a('')
a('        # Overall score')
a('        overall = float(np.mean(scores))')
a('        usable = overall > 40 and "occluded" not in issues')
a('')
a('        result = {')
a('            "score": round(overall, 1),')
a('            "blur": round(blur_score, 1),')
a('            "brightness": round(mean_brightness, 1),')
a('            "contrast": round(contrast, 1),')
a('            "issues": issues,')
a('            "usable": usable,')
a('        }')
a('        self.history.append(result)')
a('        return result')
a('')
a('    def get_trend(self) -> dict:')
a('        """Get quality trend over recent frames."""')
a('        if not self.history:')
a('            return {"avg_score": 0, "degrading": False, "samples": 0}')
a('')
a('        recent = list(self.history)')
a('        scores = [r["score"] for r in recent]')
a('        avg = np.mean(scores)')
a('')
a('        # Check if degrading (last 10 worse than first 10)')
a('        degrading = False')
a('        if len(scores) > 20:')
a('            early = np.mean(scores[:10])')
a('            late = np.mean(scores[-10:])')
a('            degrading = late < early * 0.8  # 20% worse')
a('')
a('        return {')
a('            "avg_score": round(float(avg), 1),')
a('            "min_score": round(float(min(scores)), 1),')
a('            "degrading": degrading,')
a('            "samples": len(scores),')
a('            "issue_counts": {')
a('                issue: sum(1 for r in recent if issue in r["issues"])')
a('                for issue in ("blurry", "dark", "overexposed", "low_contrast", "occluded")'),
a('            },')
a('        }')
