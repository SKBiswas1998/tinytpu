a('class BlackBoxRecorder:')
a('    """')
a('    Flight-recorder style logging for robot debugging.')
a('')
a('    Records to a binary log file:')
a('      - Timestamped detections')
a('      - Robot commands')
a('      - Safety events')
a('      - Image quality scores')
a('      - System metrics (temp, memory, FPS)')
a('')
a('    Supports:')
a('      - Circular buffer (fixed max size, overwrites oldest)')
a('      - JSON export for analysis')
a('      - Frame snapshots on events (e-stop, timeout)')
a('      - Replay: load log and feed to controller')
a('    """')
a('')
a('    def __init__(self,')
a('                 log_dir: str = "blackbox",')
a('                 max_entries: int = 10000,')
a('                 save_frames_on_event: bool = True,')
a('                 max_frame_snapshots: int = 100):')
a('        self.log_dir = log_dir')
a('        self.max_entries = max_entries')
a('        self.save_frames_on_event = save_frames_on_event')
a('        self.max_frame_snapshots = max_frame_snapshots')
a('')
a('        self.entries = deque(maxlen=max_entries)')
a('        self.frame_snapshots = deque(maxlen=max_frame_snapshots)')
a('        self.start_time = time.monotonic()')
a('        self.session_id = time.strftime("%Y%m%d_%H%M%S")')
a('        self._entry_count = 0')
a('')
a('        os.makedirs(log_dir, exist_ok=True)')
a('')
a('    def record(self, entry_type: str, data: dict, frame: np.ndarray = None):')
a('        """Record a timestamped entry."""')
a('        entry = {')
a('            "t": time.monotonic() - self.start_time,')
a('            "wall": time.time(),')
a('            "seq": self._entry_count,')
a('            "type": entry_type,')
a('            "data": data,')
a('        }')
a('        self.entries.append(entry)')
a('        self._entry_count += 1')
a('')
a('        # Save frame snapshot on important events')
a('        if frame is not None and self.save_frames_on_event:')
a('            if entry_type in ("estop", "timeout", "critical", "proximity_stop", "quality_alert"):')
a('                self.frame_snapshots.append({')
a('                    "seq": entry["seq"],')
