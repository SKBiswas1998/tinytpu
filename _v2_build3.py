a('                    "type": entry_type,')
a('                    "frame_shape": frame.shape,')
a('                })')
a('                # Save frame as numpy file')
a('                try:')
a('                    fname = os.path.join(self.log_dir, f"frame_{entry[\'seq\']:06d}.npy")')
